    "faction 字段根据角色身份自动选择（魏/蜀/吴/群/晋/神）。",
    "【繁体/简体规范】技能名称使用繁体中文，其它所有字段（称号、技能描述、背景故事、设计备注、角色名言）均使用简体中文。",
    "技能名必须严格为两个中文字符，不得带【】、[]、空格、英文、数字、标点或技能类型。",
    "必须包含 backstory 字段（80-150字背景故事）。",
    "不要解释，不要输出代码块，只输出 JSON。",
    "",
