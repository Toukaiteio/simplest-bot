export function buildSkillTunePrompt(card: SgsCardData, userInstruction: string): string {
  const skillSummary = card.skills
    .map((s, i) => `${i + 1}. [${s.type || "普通技"}] ${s.name}：${s.desc}`)
    .join("\n");

  return [
    "你是一名三国杀技能微调策划。",
    "任务：根据用户意见微调已有武将牌的技能描述。",
    "",
    "硬性边界：",
    "1. 只能调整技能 desc，不得修改技能名、技能类型、武将名、称号、势力、体力、护甲、名言、背景故事。",
    "2. 必须保留原技能的核心定位与技能间联动，不要推翻重做。",
    "3. 微调时要结合用户意见，也要加入你自己的专业判断；如果用户意见会导致无脑超模或无趣，应做克制修正。",
    "4. 每个新技能描述必须是简体中文，清楚、可执行、像真实桌游规则文本。",
    "5. 每条 desc 不超过112字；需要包含触发时机、条件、执行步骤、次数限制或代价。",
    "6. 不要输出武将完整 JSON；如果可用函数调用，必须调用 tune_sgs_skill_descriptions。",
    "",
    "当前武将：",
    `名称：${card.name}（${card.title}）/${card.faction} ${card.hp}/${card.maxHp}${card.armor > 0 ? ` 护甲${card.armor}` : ""}`,
    `技能：\n${skillSummary}`,
    `背景故事：${card.backstory}`,
    "",
    "用户微调意见：",
    userInstruction,
  ].join("\n");
}

