export function buildNicknameSimplifyPrompt(nickname: string, maxChars: number): string {
  return [
    "你负责把用户的群名片压缩成简洁的角色描述。",
    "如果名片已经是简短的名字或称号，直接返回原文。",
    "如果名片包含大量装饰符号、重复字符、超长文本，压缩成简短的角色名/称号。",
    "",
    `原始名片：${nickname}`,
    "",
    `输出要求：简述角色身份，${maxChars} 字以内，不要标点装饰。`,
  ].join("\n");
}

export function buildCardDesignPrompt(
  characterName: string,
  characterDesc: string,
  userFacts: string[] = [],
): string {
  const factsBlock = userFacts.length > 0
    ? [
        "",
        "【该用户的已知特征（来自对话记忆）】",
        ...userFacts.map((f, i) => `${i + 1}. ${f}`),
        "",
        "请结合以上用户特征进行设计，让武将技能、称号、背景故事贴合该用户的个性、喜好和经历。",
      ]
      : [];

  return [
    "你是一名专业的三国杀原创武将设计师。",
    "任务：根据以下角色描述和用户特征，设计一张原创武将牌。",
    "",
    "硬性要求：",
    "1. 不要照搬现有三国杀官方武将技能、措辞和数值模板。",
    "2. 根据角色身份自动决定势力（魏/蜀/吴/群/晋/神），输出在 faction 字段。",
    "3. 最终结果必须按指定结构提交；如果可用函数调用，必须调用 create_sgs_card，不要把 JSON 写在正文里。",
    "4. 技能描述需要清楚、可执行、尽量像真实桌游规则文本。",
    "5. 技能数量 2 到 4 个；避免每个技能都过长。",
    "6. 文本务求紧凑，避免冗词，因为最终会渲染到卡面上。",
    "7. 每个技能必须体现角色的某个核心特质，与角色身份高度相关。",
    "8. 【繁体/简体规范】技能名称使用繁体中文，其它所有字段（称号、技能描述、背景故事、设计备注、角色名言）均使用简体中文。",
    "9. 【技能名格式】技能名必须且只能是两个中文字符，如「开炮」「亮剑」；不得包含【】、[]、空格、英文、数字、标点或技能类型。",
    "10. 技能设计要有明确玩法抓手，不能只写“摸一张牌/弃一张牌/伤害+1”这类单调效果。",
    "11. 每张武将牌至少包含 1 个能形成节奏变化的机制点，如标记、蓄力、转换、判定、拼点、视为使用、额外目标、回合外响应、装备区互动、濒死收益、护甲转化、势力互动或阶段改写。",
    "12. 2-4 个技能之间要形成联动：一个核心引擎、一个防守/反制/回合外存在感、一个爆发或收束点；不要设计成互不相关的散装效果。",
    "13. 强度可以略高于标准武将，但必须有触发窗口、次数限制、代价、风险或可反制条件，避免无脑常驻压制。",
    "14. 【原创身份】武将名必须使用下方“角色名称”，不得改写成刘备、关羽、张飞、曹操、孙权、诸葛亮、司马懿、吕布等官方/历史三国人物名。",
    "15. 如果角色名称像“群友123”这类代号，仍按该代号设计原创异界武将，不要自行补成任何三国名人。",
    "",
    ...factsBlock,
    "",
    "数值约束：",
    "- hp: 1-6",
    "- maxHp: 1-6，且 maxHp >= hp",
    "- armor: 0-3",
    "",
    "技能设计指导：",
    "- 让玩家有选择：是否发动、选择目标、保留/消耗资源、提前蓄力或立刻收益。",
    "- 让对手有互动：可通过距离、手牌、装备、伤害类型、弃牌、拼点或回合时机进行规避或反制。",
    "- 让角色有成长曲线：可使用觉醒技、使命技、限定技、标记累计、失去体力后的形态变化等方式制造中后期看点。",
    "- 鼓励强而有代价的效果：额外出杀、转化锦囊、伤害改为雷/火、护甲换牌、弃置装备换爆发、受伤后反击、濒死时一次逆转。",
    "- 避免无趣模板：不要连续多个技能都只是摸牌、弃牌、回血或伤害加减；每个技能至少改变一个游戏决策。",
    "- 技能描述必须包含触发时机、条件、执行步骤、次数限制和收益/代价；限定技/觉醒技要有足够决定性的收益。",
    "",
    "create_sgs_card 参数结构：",
    "{",
    '  "name": "必须等于角色名称，1-5字",',
    '  "title": "称号，2-6字，简体中文",',
    '  "faction": "魏|蜀|吴|群|晋|神（根据角色身份自动选择）",',
    '  "hp": 3,',
    '  "maxHp": 4,',
    '  "armor": 0,',
    '  "flavor": "角色名言，12字以内的简体中文意境短句",',
    '  "skills": [',
    '    { "name": "两个中文字符的技能名，不带括号", "type": "锁定技|限定技|觉醒技|转换技|使命技|普通技", "desc": "技能描述（简体中文）" }',
    "  ],",
    '  "backstory": "角色背景故事，80-150简体中文字，要结合三国世界观，与技能和身份呼应",',
    '  "designNotes": ["最多3条，每条一句简体中文，说明设计抓手"]',
    "}",
    "",
    `角色名称：${characterName}`,
    `角色描述：${characterDesc}`,
  ].join("\n");
}

export function buildSkillValidationPrompt(card: SgsCardData): string {
  const skillSummary = card.skills
    .map((s, i) => `${i + 1}. [${s.type || "普通技"}] ${s.name}：${s.desc}`)
    .join("\n");

  return [
    "你是一名三国杀游戏平衡与规则审核专家。",
    "请审核以下武将的【技能设计】和【背景故事】是否合理。",
    "",
    "审核维度：",
    "1. 技能名称与角色身份/历史背景是否匹配",
    "2. 技能效果是否与描述文本自洽",
    "3. 技能之间是否有联动或化学反应",
    "4. 技能强度是否略强但可反制（不是无脑超模，也不是过弱无感）",
    "5. 背景故事是否与技能和身份呼应",
    "6. 技能是否有足够玩法机制，避免只有摸牌、弃牌、回血、伤害加减等单调模板",
    "7. 是否至少有一个核心机制点（标记/转换/拼点/判定/护甲/装备/阶段/回合外响应/觉醒或使命线）",
    "8. 技能名是否严格为两个中文字符，且不含【】、[]、空格、英文、数字、标点或技能类型；违反则 valid 必须为 false",
    "",
    "武将信息：",
    `名称：${card.name}（${card.title}）`,
    `势力：${card.faction}`,
    `数值：${card.hp}/${card.maxHp}${card.armor > 0 ? ` · 护甲${card.armor}` : ""}`,
    `技能：\n${skillSummary}`,
    "",
    `背景故事：${card.backstory}`,
    "",
    "请输出 JSON 格式（不要代码块）：",
    "{",
    '  "valid": true/false,',
    '  "issues": ["问题1", "问题2"],',
    '  "suggestions": ["建议1", "建议2"]',
    "}",
  ].join("\n");
}

